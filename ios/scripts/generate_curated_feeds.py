#!/usr/bin/env python3
"""Generates curated-feeds.json from the Android source of truth, DefaultFeedsConfig.kt.

Run from anywhere:  python3 ios/scripts/generate_curated_feeds.py
Parity is enforced by CuratedFeedsParityTests, which re-parses the Kotlin file and compares.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KOTLIN = ROOT / "app/src/main/java/uk/sume/streamfolio/data/network/DefaultFeedsConfig.kt"
LINK_ONLY = ROOT / "app/src/main/java/uk/sume/streamfolio/data/network/LinkOnlySources.kt"
OUT = ROOT / "ios/Packages/StreamFolioCore/Sources/StreamFolioCore/Resources/curated-feeds.json"


def link_only_constants() -> dict:
    text = LINK_ONLY.read_text()
    return {
        f"LinkOnlySources.{name}": value
        for name, value in re.findall(r'const val (\w+_FEED) = "([^"]+)"', text)
    }


def parse_feeds(text: str, constants: dict) -> list:
    body = text[text.index("private val FEEDS = mapOf("): text.index("fun getFeedsFor")]
    regions = []
    region = category = None
    for line in body.splitlines():
        stripped = line.strip()
        m = re.match(r'"([A-Z]{2})" to mapOf\($', stripped)
        if m:
            region = {"code": m.group(1), "categories": []}
            regions.append(region)
            continue
        m = re.match(r'"([^"]+)" to listOf\($', stripped)
        if m and region is not None:
            category = {"name": m.group(1), "urls": []}
            region["categories"].append(category)
            continue
        if category is None:
            continue
        m = re.match(r'"(https?://[^"]+)",?$', stripped)
        if m:
            category["urls"].append(m.group(1))
            continue
        m = re.match(r'(LinkOnlySources\.\w+),?$', stripped)
        if m:
            category["urls"].append(constants[m.group(1)])
    return regions


def parse_publisher_rules(text: str) -> list:
    body = text[text.index("fun getPublisherName"): text.index("fun getAllCuratedProviders")]
    rules = []
    for line in body.splitlines():
        m = re.match(r'\s*(url\.contains\(.+?\))\s*->\s*"([^"]+)"', line)
        if not m:
            continue
        matches = re.findall(r'url\.contains\("([^"]+)"\)', m.group(1))
        rules.append({"match": matches, "name": m.group(2)})
    return rules


def main() -> int:
    text = KOTLIN.read_text()
    data = {
        "_comment": "Generated by ios/scripts/generate_curated_feeds.py from DefaultFeedsConfig.kt. Do not edit by hand.",
        "version": 1,
        "regions": parse_feeds(text, link_only_constants()),
        "publisherRules": parse_publisher_rules(text),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    feeds = sum(len(c["urls"]) for r in data["regions"] for c in r["categories"])
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['regions'])} regions, {feeds} feed entries, {len(data['publisherRules'])} publisher rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
